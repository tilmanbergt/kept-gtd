#!/usr/bin/env node
// The quality report coverage/quality.md (docs/dev/history/technical-design-quality-assurance.md §5):
// help coverage by scenarios, help labels and quoted messages, claims by backing, diagrams.
// Needs no Jest run. Report only: it never fails a check (check.mjs --coverage runs it last).
//
//   npm run quality        write coverage/quality.md and print it

import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {collectAppStrings} from './lib/appStrings.mjs';
import {renderHelpCoverage} from './lib/helpCoverage.mjs';
import {checkLabels, demoNamesOf, extractDiagramLabels, extractLabels, extractQuotes, quoteMatches, renderLabels} from './lib/helpLabels.mjs';
import {readAppSources, readDemoFiles, readDiagramSources, readHelpCoverage, readHelpPages} from './lib/qualityInputs.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'coverage', 'quality.md');

const ts = (await import('typescript')).default;
const strings = collectAppStrings(ts, readAppSources(ROOT));
const pages = readHelpPages(ROOT);
const diagrams = readDiagramSources(ROOT);
const demoNames = demoNamesOf(await readDemoFiles(ROOT));
const allow = JSON.parse(readFileSync(join(ROOT, 'scripts', 'help-labels-allow.json'), 'utf8')).labels ?? {};

const labels = [
  ...pages.flatMap(p => extractLabels(p.markdown, `${p.id}.md`)),
  ...diagrams.flatMap(d => extractDiagramLabels(d.source, d.path.replace(/^docs\/user\//, ''))),
];
const quotes = pages.flatMap(p => extractQuotes(p.markdown, `${p.id}.md`));
const labelResult = checkLabels(labels, strings, allow);
const quoteResult = checkLabels(quotes, strings, {}, (q, s) => quoteMatches(q, s, demoNames));

const {coverage, excluded} = await readHelpCoverage(ROOT);

const sections = [
  '# Quality report',
  '',
  '> Generated by `npm run quality` (`scripts/quality-report.mjs`), not committed. Report only:',
  '> nothing here fails a check. Design: `docs/dev/history/technical-design-quality-assurance.md` §5.',
  '',
  renderHelpCoverage(coverage, excluded),
  renderLabels(labelResult, quoteResult),
  '## Claims\n\nThe claims register `docs/dev/claims.md` is not written yet.\n',
  '## Diagrams\n\nNo diagrams yet (`docs/user/diagrams/`).\n',
];
const report = sections.join('\n');
mkdirSync(dirname(OUT), {recursive: true});
writeFileSync(OUT, report, 'utf8');
console.log(report);
console.log('quality-report: wrote coverage/quality.md');
